"""Generate the M0 AUTO blocks from results/m0/pilot.json (T37, T41; CLAUDE.md §2).

    python scripts/make_tables.py            # rewrite the AUTO blocks
    python scripts/make_tables.py --check    # exit 1 if any block is out of date

Blocks: the results table in README.md and the pilot-set composition in
docs/dataset_card.md. Every number comes from the committed summary written by
scripts/run_pilot_eval.py; nothing is typed by hand. Missing values print as "—".
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "results" / "m0" / "pilot.json"
README = ROOT / "README.md"
DATASET_CARD = ROOT / "docs" / "dataset_card.md"
PILOT_BEGIN = "<!-- BEGIN AUTO: m0-pilot-set -->"
PILOT_END = "<!-- END AUTO: m0-pilot-set -->"
BEGIN = "<!-- BEGIN AUTO: m0-results -->"
END = "<!-- END AUTO: m0-results -->"


def f(x, digits=3) -> str:
    return "—" if x is None else f"{x:.{digits}f}"


def flag_everything_note(det: dict) -> str:
    """Scale reference: the response F1 of flagging every answer, from the test set's own
    label balance (precision = share of hallucinated records, recall = 1)."""
    pooled = next(iter(det.values()))["response"]["pooled"] if det else {}
    pos, n = pooled.get("positives"), pooled.get("n")
    if not pos or not n:
        return "Reference (flag every answer as hallucinated): —."
    p = pos / n
    return (
        f"Reference: flagging every answer as hallucinated gives response F1 "
        f"{f(2 * p / (1 + p))} on this test set ({pos} of {n} records hallucinated)."
    )


def render(summary: dict) -> str:
    det = summary["detection_test"]
    ret = summary["retrieval_test"]["pooled"]
    lines = [
        f"_Generated by `scripts/make_tables.py` from `results/m0/pilot.json` (run "
        f"`{summary['run_id']}`, commit `{summary['git_commit'][:7]}`). **{summary['label']}.**_",
        "",
        f"Retrieval: `{summary['embedder']['model_id']}` over the Hindi IndicQA corpus "
        f"(test questions, n = {ret['n_queries']}). NLI: `{summary['nli']['model_id']}` "
        f"(device: {summary['nli'].get('device') or '—'}). "
        f"Pilot set: {summary['pilot_records']['val']} val / {summary['pilot_records']['test']} "
        "test records (faithful vs injected NUMERICAL/TEMPORAL errors); thresholds tuned on "
        "val only.",
        "",
        "| Retrieval (test) | Recall@1 | Recall@3 | Recall@5 | Recall@10 | nDCG@10 | MRR |",
        "|---|---:|---:|---:|---:|---:|---:|",
        f"| `{summary['embedder']['name']}` | {f(ret['recall@1'])} | {f(ret['recall@3'])} | "
        f"{f(ret['recall@5'])} | {f(ret['recall@10'])} | {f(ret['ndcg@10'])} | {f(ret['mrr'])} |",
        "",
        "| Detection (pilot test) | Precision | Recall | Response F1 | Balanced acc. | AUROC "
        "| Span F1 | Token IoU | Exact-span F1 | Thresholds (entail / contradict) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    names = {
        "ours": "Ours (decompose → align → aggregate)",
        "b1_sentence_nli": "B1 sentence-level NLI",
    }
    for key, label in names.items():
        if key not in det:
            continue
        d = det[key]
        r, s = d["response"]["pooled"], d["spans"]["pooled"]
        th = d["thresholds"]
        lines.append(
            f"| {label} | {f(r.get('precision'))} | {f(r.get('recall'))} | {f(r['f1'])} | "
            f"{f(r['balanced_accuracy'])} | {f(r['auroc'])} | "
            f"{f(s['span_f1'])} | {f(s['token_iou'])} | {f(s['exact_f1'])} | "
            f"{th['entail']:.2f} / {th['contradict']:.2f} |"
        )
    lines += ["", flag_everything_note(det)]
    lines += [
        "",
        "| Span F1 by error type (pilot test) | "
        + " | ".join(names[k] for k in names if k in det)
        + " |",
        "|---|" + "---:|" * sum(k in det for k in names),
    ]
    for t in ("NUMERICAL", "TEMPORAL", "ENTITY", "LOCATION"):
        cells = [f(det[k]["spans_by_type"][t]["span_f1"]) for k in names if k in det]
        lines.append(f"| {t} | " + " | ".join(cells) + " |")
    lines.append("")
    lines.append("ENTITY/LOCATION are not injected in M0 (needs IndicNER), so they show —.")
    return "\n".join(lines) + "\n"


def render_pilot_set(summary: dict) -> str:
    """Composition of the synthetic Hindi pilot set (dataset card, T41)."""
    rec = summary["pilot_records"]
    lines = [
        f"_Generated by `scripts/make_tables.py` from `results/m0/pilot.json` (run "
        f"`{summary['run_id']}`). **{summary['label']}.**_",
        "",
        f"Records: **{rec['val']} val / {rec['test']} test** (faithful and injected records "
        "together).",
        "",
        "| Step | Count |",
        "|---|---:|",
    ]
    lines += [f"| {k} | {v} |" for k, v in sorted(summary["pilot_set"].items())]
    return "\n".join(lines) + "\n"


def replace_block(doc: str, block: str, begin: str = BEGIN, end: str = END) -> str:
    if doc.count(begin) != 1 or doc.count(end) != 1:
        raise ValueError(f"the document must contain exactly one {begin} and one {end}")
    head, rest = doc.split(begin)
    _, tail = rest.split(end)
    return f"{head}{begin}\n{block}{end}{tail}"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    summary = json.loads(SUMMARY.read_text(encoding="utf-8"))
    targets = [
        (README, render(summary), BEGIN, END),
        (DATASET_CARD, render_pilot_set(summary), PILOT_BEGIN, PILOT_END),
    ]
    stale = 0
    for path, block, begin, end in targets:
        doc = path.read_text(encoding="utf-8")
        new = replace_block(doc, block, begin, end)
        if args.check:
            if new != doc:
                print(f"{path.name}: AUTO block is out of date: run python scripts/make_tables.py")
                stale += 1
            continue
        path.write_text(new, encoding="utf-8")
        print(f"wrote {path}")
    if args.check and not stale:
        print("all M0 AUTO blocks are up to date")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
