"""The deck's expected-outcome panel, generated from results/ (T37; CLAUDE.md §3 row 20).

    python scripts/make_outcome_panel.py            # write results/m0/outcome_panel.{md,json}
    python scripts/make_outcome_panel.py --check    # exit 1 if they are out of date

Panel (deck slide 18): Macro-F1 over languages, Span F1, Recall@k, Δ over the baseline,
number of languages. Every value is read from results/m0/pilot.json; a missing input or
metric is an error, never a typed number.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "results" / "m0" / "pilot.json"
OUT = ROOT / "results" / "m0" / "outcome_panel"
RECALL_K = 10
BASELINE = "b1_sentence_nli"


class MissingResult(KeyError):
    pass


def need(d: dict, *path: str):
    cur = d
    for key in path:
        if not isinstance(cur, dict) or cur.get(key) is None:
            raise MissingResult(f"results/m0/pilot.json has no value at {'.'.join(path)}")
        cur = cur[key]
    return cur


def panel(summary: dict) -> dict:
    det = need(summary, "detection_test")
    ours_r, base_r = need(det, "ours", "response"), need(det, BASELINE, "response")
    ours_s, base_s = need(det, "ours", "spans"), need(det, BASELINE, "spans")
    return {
        "label": need(summary, "label"),
        "run_id": need(summary, "run_id"),
        "git_commit": need(summary, "git_commit"),
        "macro_f1": need(ours_r, "macro", "f1"),
        "macro_f1_languages": need(ours_r, "macro_n", "f1"),
        "worst_language_f1": need(ours_r, "worst", "f1"),
        "span_f1": need(ours_s, "pooled", "span_f1"),
        f"recall@{RECALL_K}": need(summary, "retrieval_test", "pooled", f"recall@{RECALL_K}"),
        "baseline": BASELINE,
        "delta_response_f1": need(ours_r, "pooled", "f1") - need(base_r, "pooled", "f1"),
        "delta_span_f1": need(ours_s, "pooled", "span_f1") - need(base_s, "pooled", "span_f1"),
        "n_languages": len(need(ours_r, "per_language")),
    }


def render(p: dict) -> str:
    def sign(x: float) -> str:
        return f"{x:+.3f}"

    w = p["worst_language_f1"]
    return "\n".join(
        [
            "# Expected-outcome panel (deck slide 18)",
            "",
            f"_Generated by `scripts/make_outcome_panel.py` from `results/m0/pilot.json` (run "
            f"`{p['run_id']}`, commit `{p['git_commit'][:7]}`). **{p['label']}.**_",
            "",
            "| Macro-F1 (response) | Span F1 | Recall@10 | Δ vs B1 (response F1 / span F1) "
            "| # languages |",
            "|---:|---:|---:|---:|---:|",
            f"| {p['macro_f1']:.3f} | {p['span_f1']:.3f} | {p[f'recall@{RECALL_K}']:.3f} | "
            f"{sign(p['delta_response_f1'])} / {sign(p['delta_span_f1'])} | {p['n_languages']} |",
            "",
            f"Macro-F1 averages over {p['macro_f1_languages']} language(s); worst language: "
            f"`{w['lang']}` ({w['value']:.3f}). Δ = ours − B1 (sentence-level NLI) on the pilot "
            "test set.",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    if not SUMMARY.exists():
        print(f"missing {SUMMARY}: run scripts/run_pilot_eval.py first", file=sys.stderr)
        return 2
    try:
        p = panel(json.loads(SUMMARY.read_text("utf-8")))
    except MissingResult as e:
        print(e.args[0], file=sys.stderr)
        return 2
    files = {
        OUT.with_suffix(".md"): render(p),
        OUT.with_suffix(".json"): json.dumps(p, ensure_ascii=False, indent=2, sort_keys=True)
        + "\n",
    }
    if args.check:
        stale = [f for f, text in files.items() if not f.exists() or f.read_text("utf-8") != text]
        for f in stale:
            print(f"{f.relative_to(ROOT)} is out of date: run python scripts/make_outcome_panel.py")
        return 1 if stale else 0
    for f, text in files.items():
        f.write_text(text, "utf-8")
        print(f"wrote {f.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
