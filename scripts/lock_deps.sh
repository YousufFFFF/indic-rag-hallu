#!/usr/bin/env sh
# Regenerate requirements-lock.txt from the pins in pyproject.toml.
# Resolves inside the same pinned base image the Dockerfile uses, so the lock
# matches the dev container exactly. Run from the repo root:
#   sh scripts/lock_deps.sh
set -eu

IMAGE="python:3.11-slim@sha256:07d4824036af339fa1b6ef769cc99d9c10a141769538b52b3b597c84f7a7b535"

# MSYS_NO_PATHCONV stops Git Bash on Windows from rewriting the container paths.
MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd):/src:ro" "$IMAGE" sh -c '
  set -eu
  cp -r /src /tmp/build
  pip install -q --disable-pip-version-check \
    --index-url https://download.pytorch.org/whl/cpu \
    --extra-index-url https://pypi.org/simple \
    "/tmp/build[dev]" >&2
  echo "# Generated by scripts/lock_deps.sh from pyproject.toml - do not edit by hand."
  echo "# Python $(python -c "import platform; print(platform.python_version())"), linux/x86_64, CPU torch."
  pip freeze --exclude indichallu
' > requirements-lock.txt

echo "Wrote requirements-lock.txt ($(grep -vc '^#' requirements-lock.txt) packages)"
