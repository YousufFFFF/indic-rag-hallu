"""Corpus statistics per language, and rendering them into the dataset card.

Two steps, so that every number in the card comes from a committed results file
(CLAUDE.md §2: no hand-typed numbers):

1. :func:`compute_language_stats` (needs the downloaded data) -> a JSON-able dict, saved
   to ``results/corpus_stats/indicqa.json`` by ``scripts/corpus_stats.py compute``.
2. :func:`render_tables` turns that JSON into Markdown, which
   :func:`replace_block` writes between ``<!-- BEGIN AUTO: corpus-stats -->`` and
   ``<!-- END AUTO: corpus-stats -->`` in ``docs/dataset_card.md``.
"""

from __future__ import annotations

import statistics
from pathlib import Path
from typing import Any

from indichallu.data.loaders.indicqa import IndicQA
from indichallu.data.schema import Split
from indichallu.data.split import SplitConfig, split_dataset, split_stats
from indichallu.languages import Language
from indichallu.text.sentseg import sentences, tokens

REPO_ROOT = Path(__file__).resolve().parents[3]
STATS_JSON = REPO_ROOT / "results" / "corpus_stats" / "indicqa.json"
DATASET_CARD = REPO_ROOT / "docs" / "dataset_card.md"
BEGIN = "<!-- BEGIN AUTO: corpus-stats -->"
END = "<!-- END AUTO: corpus-stats -->"
OFFSET_STATUSES = ("exact", "unique", "nearest", "ambiguous", "not_found")


def _median(values: list[int]) -> float:
    return float(statistics.median(values)) if values else 0.0


def compute_language_stats(ds: IndicQA, lang: Language, split_config: SplitConfig) -> dict:
    """All per-language numbers for the dataset card, as plain JSON types."""
    passage_chars = [len(p.text) for p in ds.passages]
    passage_tokens = [len(tokens(p.text)) for p in ds.passages]
    passage_sents = [len(sentences(p.text, ds.lang)) for p in ds.passages]
    question_tokens = [len(tokens(q.question)) for q in ds.questions]
    assignment = split_dataset(ds, split_config)
    per_split = split_stats(ds, assignment)
    answerable = sum(q.answerable for q in ds.questions)
    return {
        "lang": ds.lang,
        "name": lang.name,
        "family": lang.family.value,
        "enabled": lang.enabled,
        "passages": len(ds.passages),
        "questions": len(ds.questions),
        "answerable": answerable,
        "unanswerable": len(ds.questions) - answerable,
        "answer_offsets": {s: ds.stats[s] for s in OFFSET_STATUSES},
        "median_passage_chars": _median(passage_chars),
        "median_passage_tokens": _median(passage_tokens),
        "median_passage_sentences": _median(passage_sents),
        "median_question_tokens": _median(question_tokens),
        "splits": {
            s.value: {k: per_split[s][k] for k in ("passages", "questions", "unanswerable")}
            for s in (Split.TRAIN, Split.VAL, Split.TEST)
        },
    }


# --- rendering -------------------------------------------------------------------------


def _n(x: float) -> str:
    return f"{x:,.0f}" if float(x).is_integer() else f"{x:,.1f}"


def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.1f}%" if whole else "—"


def render_tables(stats: dict[str, Any], languages: dict[str, Language]) -> str:
    """Markdown tables for every configured language (missing ones marked as such)."""
    by_lang = stats.get("languages", {})
    prov = stats.get("provenance", {})
    ratios = prov.get("split_ratios") or {}
    ratio_text = " / ".join(f"{k} {ratios[k]:g}" for k in ("train", "val", "test") if k in ratios)
    lines = [
        "_Generated by `scripts/corpus_stats.py` from `results/corpus_stats/indicqa.json`;"
        " do not edit by hand._",
        "",
        f"Source: `{prov.get('repo', '?')}` @ `{prov.get('revision', '?')[:12]}`"
        f" ({prov.get('licence', '?')}). Split: seed {prov.get('split_seed', '?')},"
        f" {ratio_text or '?'}, grouped by {prov.get('split_group_by', '?')}."
        " Tokens and sentences come from `indichallu.text.sentseg`.",
        "",
        "### Corpus",
        "",
        "| Language | Family | In M0 | Passages | Questions | Answerable | Unanswerable"
        " | Median passage (chars / tokens / sentences) | Median question (tokens) |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for code, lang in languages.items():
        s = by_lang.get(code)
        if s is None:
            lines.append(
                f"| {lang.name} (`{code}`) | {lang.family.value} | — | not computed | | | | | |"
            )
            continue
        lines.append(
            f"| {s['name']} (`{code}`) | {s['family']} | {'yes' if s['enabled'] else 'no'}"
            f" | {_n(s['passages'])} | {_n(s['questions'])}"
            f" | {_n(s['answerable'])} ({_pct(s['answerable'], s['questions'])})"
            f" | {_n(s['unanswerable'])} ({_pct(s['unanswerable'], s['questions'])})"
            f" | {_n(s['median_passage_chars'])} / {_n(s['median_passage_tokens'])}"
            f" / {_n(s['median_passage_sentences'])} | {_n(s['median_question_tokens'])} |"
        )
    lines += [
        "",
        "### Answer offsets (see DECISIONS D-017)",
        "",
        "Answerable questions only. *Given offset correct*: the source `answer_start` already"
        " points at the answer. *Realigned*: the answer text occurs once in the passage"
        " (unique) or is clearly the nearest occurrence after the given offset (nearest)."
        " *No offset*: kept as questions, but their answer span is not used.",
        "",
        "| Language | Answerable | Given offset correct | Realigned (unique / nearest)"
        " | No offset (ambiguous / not found) |",
        "|---|---:|---:|---:|---:|",
    ]
    for s in (by_lang[c] for c in languages if c in by_lang):
        o, a = s["answer_offsets"], s["answerable"]
        lines.append(
            f"| {s['name']} | {_n(a)} | {_n(o['exact'])} ({_pct(o['exact'], a)})"
            f" | {_n(o['unique'])} / {_n(o['nearest'])}"
            f" ({_pct(o['unique'] + o['nearest'], a)})"
            f" | {_n(o['ambiguous'])} / {_n(o['not_found'])}"
            f" ({_pct(o['ambiguous'] + o['not_found'], a)}) |"
        )
    lines += [
        "",
        "### Splits (passages / questions / unanswerable)",
        "",
        "| Language | Train | Val | Test |",
        "|---|---:|---:|---:|",
    ]
    for s in (by_lang[c] for c in languages if c in by_lang):
        cells = [
            f"{_n(v['passages'])} / {_n(v['questions'])} / {_n(v['unanswerable'])}"
            for v in (s["splits"][k] for k in ("train", "val", "test"))
        ]
        lines.append(f"| {s['name']} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def replace_block(document: str, block: str) -> str:
    """Replace the text between the BEGIN/END markers; everything else is kept."""
    if document.count(BEGIN) != 1 or document.count(END) != 1:
        raise ValueError(f"document must contain exactly one {BEGIN} and one {END}")
    head, rest = document.split(BEGIN)
    _, tail = rest.split(END)
    return f"{head}{BEGIN}\n{block}{END}{tail}"
